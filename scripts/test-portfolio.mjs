import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createBrowserSession } from './browser-fixtures.mjs';
import { groupProjects } from '../resources/js/portfolioReports.js';
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const { page, context } = await createBrowserSession(browser, { admin: true, dismissNotice: true, onError: e => errors.push(e) });
  await page.route('**/api/v1/projects/1/financial-result', route => route.fulfill({ status: 503, json: { message: 'Detalhamento indisponível' } }));
  const go = async () => {
    await page.locator('.dashboard-sidebar').getByRole('button', { name: 'Portfólios', exact: true }).click();
    await page.locator('.portfolio-project-cards button').waitFor();
  };
  await go();
  assert.equal(await page.locator('.analytics-kpis').count(), 1);
  assert.equal(await page.locator('.project-detail-analytics').count(), 0);
  await page.locator('.portfolio-project-cards button').click();
  await page.locator('.portfolio-builder').waitFor();
  assert.equal(await page.locator('.analytics-kpis').count(), 0);
  await page.getByRole('button', { name: 'Personalizar painel', exact: true }).click();
  await page.getByLabel('Visualização: Visão financeira', { exact: true }).selectOption('table');
  await page.locator('.portfolio-widget-picker').getByLabel('Consumo de horas', { exact: true }).uncheck();
  assert.equal(await page.locator('.portfolio-data-table tbody tr').count(), 4);
  assert.equal(await page.locator('.portfolio-widget-grid > article').count(), 5);
  await page.getByRole('button', { name: '← Visão de portfólio', exact: true }).click();
  await page.locator('.portfolio-project-cards button').click();
  assert.equal(await page.locator('.portfolio-data-table').count(), 1);
  assert.equal(await page.locator('.portfolio-widget-grid > article').count(), 5);
  await page.getByRole('button', { name: '← Visão de portfólio', exact: true }).click();
  await page.locator('.analytics-filters input').first().fill('2026-10-26');
  await page.locator('.analytics-filters input').nth(1).fill('2026-01-01');
  await page.getByRole('button', { name: 'Aplicar período', exact: true }).click();
  await page.getByText('A data final deve ser igual ou posterior à data inicial.', { exact: true }).waitFor();
  await page.route('**/api/v1/projects/1/financial-result', route => route.fulfill({ json: { actual: { taxes: 100, commission: 50, labor_cost: 300, approved_expenses: 50, profit: -500 }, estimated: { minutes: 2400, profit: 800 }, by_analyst: [{ name: 'Ana Teste', cost: 300, minutes: 600 }], by_activity_type: [{ name: 'Análise', minutes: 600, cost: 300 }], complete: true } }));
  await page.locator('.portfolio-project-cards button').click();
  await page.locator('.management-report').waitFor();
  assert.equal(await page.locator('.portfolio-widget-grid').getByText('Aguardando detalhamento financeiro.', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Personalizar painel', exact: true }).click();
  await page.getByRole('button', { name: 'Mostrar todos', exact: true }).click();
  assert.ok(await page.locator('.portfolio-widget-grid > article').count() >= 24);
  const finance = page.locator('.portfolio-widget').filter({ has: page.getByRole('heading', { name: 'Visão financeira', exact: true }) });
  const select = finance.getByLabel('Visualização: Visão financeira', { exact: true });
  const types = await select.locator('option').evaluateAll(options => options.map(option => option.value));
  assert.equal(types.length, 11);
  for (const type of types) {
    await select.selectOption(type);
    assert.ok((await finance.innerText()).length > 30);
    assert.equal(await finance.locator('[d*="NaN"], [points*="NaN"]').count(), 0);
    if (type === 'table') assert.equal(await finance.locator('tbody tr').count(), 4);
    else if (['columns', 'line', 'area', 'radar'].includes(type)) assert.equal(await finance.locator('svg').count(), 1);
    else if (['pie', 'donut'].includes(type)) assert.equal(await finance.locator('.portfolio-pie').count(), 1);
  }
  const downloadPromise = page.waitForEvent('download');
  await finance.getByRole('button', { name: 'Exportar CSV', exact: true }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'financial.csv');
  const stream = await download.createReadStream();
  let csv = ''; for await (const chunk of stream) csv += chunk.toString();
  assert.ok(csv.includes('Contrato')); assert.ok(csv.includes('12000'));
  const profit = page.locator('.portfolio-widget').filter({ has: page.getByRole('heading', { name: 'Lucro planejado e realizado', exact: true }) });
  await profit.getByLabel('Visualização: Lucro planejado e realizado', { exact: true }).selectOption('pie');
  await profit.getByText('Esta visualização exige valores positivos. Use barras, linhas ou tabela para mostrar prejuízos.', { exact: true }).waitFor();
  assert.match(await profit.locator('tbody').innerText(), /-.*500/);
  await page.getByRole('button', { name: '← Visão de portfólio', exact: true }).click();
  await page.getByRole('button', { name: 'Personalizar painel', exact: true }).click();
  await page.locator('.portfolio-widget-picker').getByLabel('Levantamento personalizado', { exact: true }).check();
  const custom = page.locator('.portfolio-widget').filter({ has: page.getByRole('heading', { name: 'Levantamento personalizado', exact: true }) });
  await custom.getByLabel('Medida', { exact: true }).selectOption('profit');
  await custom.getByLabel('Agrupar por', { exact: true }).selectOption('client');
  await custom.getByLabel('Agregação', { exact: true }).selectOption('average');
  await custom.getByLabel('Visualização: Levantamento personalizado', { exact: true }).selectOption('table');
  assert.ok((await custom.locator('tbody').innerText()).includes('Cliente Teste'));
  await page.getByRole('button', { name: 'Ocultar todos', exact: true }).click();
  assert.equal(await page.locator('.portfolio-widget').count(), 0);
  await page.getByRole('button', { name: 'Restaurar padrão', exact: true }).click();
  assert.equal(await page.locator('.portfolio-widget').count(), 6);
  const sample = [{ id: 1, client: 'A', profit: -10 }, { id: 2, client: 'A', profit: 30 }, { id: 3, client: 'B', profit: null }];
  assert.deepEqual(groupProjects(sample, 'client', 'profit', 'average'), [{ label: 'A', value: 10 }, { label: 'B', value: null }]);
  assert.equal(groupProjects(sample, 'client', 'profit', 'min')[0].value, -10);
  assert.equal(groupProjects(sample, 'client', 'profit', 'max')[0].value, 30);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '/tmp/spot-portfolio-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  await context.close();
  console.log('Portfolio passed: overview, project reports, all 11 chart types, CSV contents, negative values, aggregations, missing data, saved preferences, date validation and mobile layout.');
} finally { await browser.close(); }
